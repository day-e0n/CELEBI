#!/usr/bin/env python3
"""Experiment B (part 2): does the fixed-page cache actually reuse data across
same-template, different-parameter query instances (as query_signature()'s
column-only Sig() would assume, since it ignores filter literals)?

Runs two Q8 (TPC-H "national market share") variants generated by the official
TPC-H query generator (test_datasets/tpch-dbgen/qgen) with different region /
part-type substitution parameters:

  A (seed=1): region=AFRICA,  part_type='PROMO POLISHED TIN'
  B (seed=2): region=ASIA,    part_type='PROMO BURNISHED TIN'
  C (seed=3): region=AFRICA,  part_type='ECONOMY BRUSHED TIN'   (same region as A)

Sequence 1 "repeat":    A, A, A   -- identical params every time
Sequence 2 "vary":      A, B, C   -- same template, different params each time

Both run under the same paging config used for the paper's headline run. Each
execution is labeled via sirius_set_query_label so its log segment can be
inspected for [fixed-page-cache] auto_cache_populate / using page-backed
cached provider / auto_cache_skip lines on the `region` and `part` scans --
the tables carrying literal (static) filters in Q8 -- to see hit vs miss
directly, independent of the wall-clock noise on tiny tables.
"""

