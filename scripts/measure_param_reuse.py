def make_env(devices: str, log_dir: Path, config_path: Path) -> dict[str, str]:
    env = os.environ.copy()
    env["CUDA_VISIBLE_DEVICES"] = devices
    env["SIRIUS_CONFIG_FILE"] = str(config_path)
    env["SIRIUS_LOG_DIR"] = str(log_dir)
    env["SIRIUS_LOG_LEVEL"] = "info"
    env["SIRIUS_ENABLE_FIXED_PAGE_REUSE"] = "1"
    env["SIRIUS_FIXED_PAGE_AUTO_CACHE"] = "1"
    env["SIRIUS_FIXED_PAGE_AUTO_CACHE_ROUND_ROBIN_CHUNKS"] = "1"
    env["SIRIUS_FIXED_PAGE_VIEW_ALIGNED_SPLITS"] = "1"
    env["SIRIUS_FIXED_PAGE_PRUNING"] = "1"
    env["SIRIUS_FIXED_PAGE_OWNED_PAGES"] = "1"
    env["SIRIUS_FIXED_PAGE_DEMAND_LOAD"] = "1"
    env["SIRIUS_FIXED_PAGE_BACKED_PROVIDER"] = "1"
    env["SIRIUS_FIXED_PAGE_HYBRID_PROVIDER"] = "1"
    env["SIRIUS_FIXED_PAGE_CACHE_BYTES_PER_GPU"] = "3GB"
    return env


def write_config(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        "sirius:\n"
        "  topology:\n"
        "    num_gpus: 1\n"
        "  memory:\n"
        "    gpu:\n"
        "      usage_limit_bytes: 20GB\n"
        "      reservation_limit_fraction: 0.85\n"
        "    host:\n"
        "      capacity_bytes: 32GB\n"
    )


def run_sequence(con, seq_name: str, letters: list[str]) -> None:
    for i, letter in enumerate(letters, start=1):
        label = f"{seq_name}_{letter}_pos{i}"
        con.execute(f"CALL sirius_set_query_label('{label}')")
        con.execute("SET gpu_execution = true;")
        rows = con.execute(VARIANTS[letter]["sql"]).fetchall()
        print(f"[{seq_name}] pos{i} variant={letter} region={VARIANTS[letter]['region']} "
              f"part_type={VARIANTS[letter]['part_type']} rows={len(rows)}", flush=True)


def analyze_log(log_path: Path) -> None:
    lines = log_path.read_text(errors="replace").splitlines()

    def segment(label: str) -> list[str]:
        starts = [i for i, l in enumerate(lines) if f"sirius_set_query_label('{label}')" in l]
        if not starts:
            return []
        i = starts[0]
        end = len(lines)
        for j in range(i + 1, len(lines)):
            if "sirius_set_query_label(" in lines[j]:
                end = j
                break
        return lines[i:end]

    print()
    print("=" * 100)
    print(f"{'label':<18}{'region_event':<28}{'part_event':<28}{'region_dur_us':>15}{'part_dur_us':>13}")
    print("=" * 100)
    for seq_name in ("repeat", "vary"):
        for i in range(1, 4):
            letter = {"repeat": ["A", "A", "A"], "vary": ["A", "B", "C"]}[seq_name][i - 1]
            label = f"{seq_name}_{letter}_pos{i}"
            seg = segment(label)
            region_event, part_event = "none", "none"
            region_dur, part_dur = "-", "-"
            for l in seg:
                if "region.parquet" in l:
                    if "parquet_materialize" in l:
                        region_event = "MISS(materialize)"
                        m = re.search(r"duration_us=(\d+)", l)
                        if m:
                            region_dur = m.group(1)
                if "part.parquet" in l:
                    if "parquet_materialize" in l:
                        part_event = "MISS(materialize)"
                        m = re.search(r"duration_us=(\d+)", l)
                        if m:
                            part_dur = m.group(1)
                if "using page-backed" in l or "using hybrid page/chunk" in l:
                    if "region" in l.lower():
                        region_event = "HIT(cached provider)"
                    elif "part" in l.lower():
                        part_event = "HIT(cached provider)"
            print(f"{label:<18}{region_event:<28}{part_event:<28}{region_dur:>15}{part_dur:>13}")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", default="/mnt/nvme/sirius_tpch/tpch_parquet_sf30_optimized")
    parser.add_argument("--devices", default="0")
    parser.add_argument("--output", type=Path, default=REPO_ROOT / "experiment" / "fixed_page_runs" / "expB_param_reuse")
    args = parser.parse_args()

    output = args.output.resolve()
    log_dir = output / "log_dir"
    log_dir.mkdir(parents=True, exist_ok=True)
    config_path = output / "sirius.yaml"
    write_config(config_path)
    env = make_env(args.devices, log_dir, config_path)
    os.environ.update(env)

    con = open_connection(args.input, gpu_execution=True)
    try:
        print("--- sequence 1: repeat (A, A, A) -- identical params ---")
        run_sequence(con, "repeat", ["A", "A", "A"])
        print()
        print("--- sequence 2: vary (A, B, C) -- different params each time ---")
        run_sequence(con, "vary", ["A", "B", "C"])
    finally:
        con.close()

    log_files = sorted(log_dir.glob("*.log"))
    if log_files:
        analyze_log(log_files[-1])
    else:
        print("no log file produced")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
