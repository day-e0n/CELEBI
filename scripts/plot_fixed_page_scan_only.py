#!/usr/bin/env python3
"""Plot scan-only fixed-page paging comparisons.

Consumes the query/workload summary CSVs generated by
scripts/run_fixed_page_workload_sequence.py and emits compact figures focused on
scan/materialization cost rather than end-to-end latency.
"""

from __future__ import annotations

import argparse
import csv
from pathlib import Path


def to_float(value: object) -> float:
    try:
        if value in (None, ""):
            return 0.0
        return float(value)
    except Exception:
        return 0.0


def to_int(value: object) -> int:
    try:
        if value in (None, ""):
            return 0
        return int(float(value))
    except Exception:
        return 0


def read_rows(path: Path) -> list[dict[str, str]]:
    with path.open(newline="") as f:
        return list(csv.DictReader(f))


def write_csv(path: Path, rows: list[dict[str, object]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fields: list[str] = []
    for row in rows:
        for key in row:
            if key not in fields:
                fields.append(key)
    with path.open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)


def pick_baseline_series(rows: list[dict[str, str]], requested: str) -> str:
    series = {row.get("series", "") for row in rows}
    if requested != "auto":
        return requested
    if "baseline" in series:
        return "baseline"
    if "hot" in series:
        return "hot"
    if "cold" in series:
        return "cold"
    raise SystemExit("could not infer baseline series")


def reduction_ratio(base: float, target: float) -> float:
    return (base - target) / base if base else 0.0


def build_query_scan_rows(
    rows: list[dict[str, str]],
    baseline_series: str,
    target_series: str,
) -> list[dict[str, object]]:
    by_key = {(row.get("series", ""), to_int(row.get("position"))): row for row in rows}
    positions = sorted({to_int(row.get("position")) for row in rows if row.get("series") == baseline_series})
    out: list[dict[str, object]] = []
    for pos in positions:
        base = by_key.get((baseline_series, pos))
        target = by_key.get((target_series, pos))
        if not base or not target:
            continue
        base_scan = to_float(base.get("scan_materialize_work_ms"))
        target_scan = to_float(target.get("scan_materialize_work_ms"))
        base_scan_wall = to_float(base.get("scan_wall_ms"))
        target_scan_wall = to_float(target.get("scan_wall_ms"))
        base_load = to_float(base.get("load_ms"))
        target_load = to_float(target.get("load_ms"))
        out.append({
            "position": pos,
            "query": base.get("query", f"q{pos}"),
            "baseline_series": baseline_series,
            "target_series": target_series,
            "baseline_scan_materialize_work_ms": base_scan,
            "target_scan_materialize_work_ms": target_scan,
            "scan_materialize_work_saved_ms": base_scan - target_scan,
            "scan_materialize_work_reduction_ratio": reduction_ratio(base_scan, target_scan),
            "baseline_scan_wall_ms": base_scan_wall,
            "target_scan_wall_ms": target_scan_wall,
            "scan_wall_saved_ms": base_scan_wall - target_scan_wall,
            "scan_wall_reduction_ratio": reduction_ratio(base_scan_wall, target_scan_wall),
            "baseline_load_ms": base_load,
            "target_load_ms": target_load,
            "load_saved_ms": base_load - target_load,
            "load_reduction_ratio": reduction_ratio(base_load, target_load),
        })
    return out


def build_workload_scan_rows(
    rows: list[dict[str, str]],
    baseline_series: str,
    target_series: str,
) -> list[dict[str, object]]:
    by_series = {row.get("series", ""): row for row in rows}
    base = by_series.get(baseline_series)
    target = by_series.get(target_series)
    if not base or not target:
        return []
    metrics = [
        ("scan_materialize_work_ms", "Scan Materialize Work"),
        ("scan_wall_ms", "Scan Wall"),
        ("load_ms", "Load/Materialize Wall"),
    ]
    out: list[dict[str, object]] = []
    for field, label in metrics:
        base_value = to_float(base.get(field))
        target_value = to_float(target.get(field))
        out.append({
            "metric": field,
            "label": label,
            "baseline_series": baseline_series,
            "target_series": target_series,
            "baseline_ms": base_value,
            "target_ms": target_value,
            "saved_ms": base_value - target_value,
            "reduction_ratio": reduction_ratio(base_value, target_value),
        })
    return out


def plot_query_scan(rows: list[dict[str, object]], out: Path, title: str) -> None:
    import matplotlib.pyplot as plt
    import numpy as np

    labels = [str(row["query"]) for row in rows]
    x = np.arange(len(labels))
    width = 0.36

    fig, ax = plt.subplots(figsize=(max(14, len(labels) * 0.72), 7.2), constrained_layout=True)
    base = np.array([to_float(row["baseline_scan_materialize_work_ms"]) for row in rows])
    target = np.array([to_float(row["target_scan_materialize_work_ms"]) for row in rows])
    ax.bar(x - width / 2, base, width=width, label="baseline scan work", color="#4c78a8")
    ax.bar(x + width / 2, target, width=width, label="paging scan work", color="#59a14f")
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=35, ha="right", fontsize=16)
    ax.set_ylabel("Scan/materialize work (ms)", fontsize=17)
    ax.set_title(title, fontsize=21, pad=14)
    ax.tick_params(axis="y", labelsize=15)
    ax.grid(axis="y", alpha=0.24)
    ax.legend(loc="upper center", bbox_to_anchor=(0.5, 1.13), ncols=2, frameon=False, fontsize=16)
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=180)
    plt.close(fig)


