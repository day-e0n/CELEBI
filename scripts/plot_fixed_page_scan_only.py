def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--query-summary", type=Path, required=True)
    parser.add_argument("--workload-summary", type=Path, required=True)
    parser.add_argument("--out-dir", type=Path, default=Path("experiment/graph"))
    parser.add_argument("--prefix", required=True)
    parser.add_argument("--baseline-series", default="auto")
    parser.add_argument("--target-series", default="paging")
    parser.add_argument("--title-prefix", default="")
    args = parser.parse_args()

    query_rows = read_rows(args.query_summary)
    workload_rows = read_rows(args.workload_summary)
    baseline_series = pick_baseline_series(query_rows, args.baseline_series)
    target_series = args.target_series
    title_prefix = f"{args.title_prefix}: " if args.title_prefix else ""

    scan_rows = build_query_scan_rows(query_rows, baseline_series, target_series)
    workload_scan_rows = build_workload_scan_rows(workload_rows, baseline_series, target_series)
    if not scan_rows:
        raise SystemExit("no query scan rows to plot")
    if not workload_scan_rows:
        raise SystemExit("no workload scan rows to plot")

    write_csv(args.out_dir / f"{args.prefix}_scan_only_query.csv", scan_rows)
    write_csv(args.out_dir / f"{args.prefix}_scan_only_workload.csv", workload_scan_rows)
    plot_query_scan(
        scan_rows,
        args.out_dir / f"{args.prefix}_scan_only_query_scan_work.png",
        f"{title_prefix}per-query scan/materialize work",
    )
    plot_query_scan_saved(
        scan_rows,
        args.out_dir / f"{args.prefix}_scan_only_query_saved.png",
        f"{title_prefix}scan/materialize work saved by paging",
    )
    plot_query_scan_latency(
        scan_rows,
        args.out_dir / f"{args.prefix}_scan_only_query_scan_latency.png",
        f"{title_prefix}per-query scan latency",
    )
    plot_query_scan_latency_saved(
        scan_rows,
        args.out_dir / f"{args.prefix}_scan_only_query_scan_latency_saved.png",
        f"{title_prefix}scan latency saved by paging",
    )
    plot_workload_scan(
        workload_scan_rows,
        args.out_dir / f"{args.prefix}_scan_only_workload_totals.png",
        f"{title_prefix}workload scan/load totals",
    )
    print(f"wrote {args.out_dir / (args.prefix + '_scan_only_query.csv')}")
    print(f"wrote {args.out_dir / (args.prefix + '_scan_only_query_scan_work.png')}")
    print(f"wrote {args.out_dir / (args.prefix + '_scan_only_query_saved.png')}")
    print(f"wrote {args.out_dir / (args.prefix + '_scan_only_query_scan_latency.png')}")
    print(f"wrote {args.out_dir / (args.prefix + '_scan_only_query_scan_latency_saved.png')}")
    print(f"wrote {args.out_dir / (args.prefix + '_scan_only_workload_totals.png')}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
