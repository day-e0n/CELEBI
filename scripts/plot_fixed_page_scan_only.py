    ax.bar(x, saved, width=0.62, color=colors)
    ax.axhline(0, color="#333333", linewidth=1.0)
    ax.set_xticks(x)
    ax.set_xticklabels(labels, rotation=35, ha="right", fontsize=16)
    ax.set_ylabel("Scan work saved by paging (ms)", fontsize=17)
